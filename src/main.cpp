USBHIDKeyboard Keyboard;

void setup() {
  USB.VID(0x303A);   // Espressif VID (safe)
  USB.PID(0x4001);
  USB.manufacturerName("Logitech");
  USB.productName("G513 RGB");
  USB.serialNumber("1488_Balazs");

  USB.begin();        // MUST be before Serial
  Keyboard.begin();   // Registers HID

  Serial.begin(115200);
  delay(2000);
  Serial.println("ESP32-S3 HID keyboard ready");
}

void loop() {
  if (Serial.available()) {
    char c = Serial.read();

    if (c >= 32 && c <= 126) {
      Keyboard.write(c);  // press + release
    }
    if (c == '\n') {
      Keyboard.write(KEY_RETURN);
    }
  }
}
